// Serialises the preview's three exercises for the static build.
//
// The preview used to ship whole courses plus the schema library and re-check
// them in the visitor's browser on every load: about 650 KB of a 930 KB
// bundle, for content that is fixed when we build. Validation happens here,
// once, with the same schema; the phone receives plain data.
//
// Output: dist/preview-data/skill-preview.js, which scripts/build-rehearsal.mjs
// substitutes for src/content/skill-preview.ts. It exports the same names.
//
//   tsx scripts/extract-preview.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { isDeepStrictEqual } from "node:util";
import { callPractice, getSkillPreview } from "@/content/skill-preview";

const previews = { cost: getSkillPreview("cost"), digital: getSkillPreview("digital") };
const data = { previews, callPractice };

// Anything JSON cannot carry (a Date, a RegExp, undefined in an array) would
// arrive in the browser as something else and silently change grading. Refuse.
if (!isDeepStrictEqual(JSON.parse(JSON.stringify(data)), data)) {
  throw new Error(
    "Preview content does not survive JSON serialisation; refusing to build a preview that grades differently.",
  );
}
for (const [skill, preview] of Object.entries(previews)) {
  if (!preview) throw new Error(`No preview content for "${skill}".`);
}

const json = JSON.stringify(data);
mkdirSync("dist/preview-data", { recursive: true });
writeFileSync(
  "dist/preview-data/skill-preview.js",
  `// Generated by scripts/extract-preview.ts. Do not edit.
const data = ${json};
export const callPractice = data.callPractice;
export function getSkillPreview(skill) {
  return Object.hasOwn(data.previews, skill) ? data.previews[skill] : null;
}
`,
);
console.log(`Preview content: ${(json.length / 1024).toFixed(1)} KB`);
